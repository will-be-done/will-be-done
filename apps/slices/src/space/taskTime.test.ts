import { afterEach, describe, expect, it, vi } from "vitest";
import {
  createAction,
  DB,
  execSync,
  insert,
  selectFrom,
  selectSync,
  syncDispatch,
} from "@will-be-done/hyperdb";
import { BptreeInmemDriver } from "@will-be-done/hyperdb/drivers/inmemory";
import { dbIdTrait } from "../traits";
import { getSpaceBackup, loadSpaceBackup, type Backup } from "./backup";
import {
  dailyEntryByTaskId,
  datedEntriesByDates,
  removeFromDailyList,
  scheduleTask,
} from "./dailyEntries";
import { dailyListByDate } from "./dailyLists";
import { taskById, updateTask } from "./tasks";
import {
  createTaskTemplateFromTask,
  generateTasksForTemplate,
  taskTemplateUpcomingOccurrences,
  updateTemplate,
} from "./taskTemplates";
import { registeredSpaceSyncableTables } from "./syncMap";
import {
  dailyEntriesTable,
  tasksTable,
  taskTemplatesTable,
  type DailyEntry,
  type Task,
  type TaskTemplate,
} from "./tables";

const action = createAction();

function createDB() {
  vi.spyOn(Date.prototype, "getTimezoneOffset").mockReturnValue(0);
  const db = new DB(new BptreeInmemDriver(), {
    traits: [dbIdTrait("space", "a0000000-0000-4000-8000-000000000001")],
  });
  execSync(db.loadTables(registeredSpaceSyncableTables));
  return db;
}

function insertRows(
  db: DB,
  rows: { tasks?: Task[]; templates?: TaskTemplate[] },
) {
  syncDispatch(
    db,
    action({
      name: "insertTaskTimeRows",
      args: {},
      handler: function* () {
        if (rows.tasks) yield* insert(tasksTable, rows.tasks);
        if (rows.templates) yield* insert(taskTemplatesTable, rows.templates);
      },
    })({}),
  );
}

function allRows(db: DB) {
  return syncDispatch(
    db,
    action({
      name: "readTaskTimeRows",
      args: {},
      handler: function* () {
        return {
          tasks: (yield* selectFrom(tasksTable, "byIds")) as Task[],
          entries: (yield* selectFrom(
            dailyEntriesTable,
            "byIds",
          )) as DailyEntry[],
        };
      },
    })({}),
  );
}

function entryOf(db: DB, taskId: string) {
  return selectSync(db, { selector: dailyEntryByTaskId, args: { taskId } });
}

const task = (id: string): Task => ({
  type: "task",
  id,
  title: id,
  state: "todo",
  projectSectionId: "section-1",
  orderToken: "a0",
  lastToggledAt: 0,
  createdAt: 0,
  nature: "unknown",
  templateId: null,
  templateDate: null,
});

const template = (overrides: Partial<TaskTemplate>): TaskTemplate => ({
  type: "template",
  id: "template-1",
  title: "Standup",
  orderToken: "a0",
  repeatRule: "FREQ=DAILY;INTERVAL=1",
  repeatRuleDtStart: Date.parse("2026-03-01T00:00:00Z"),
  createdAt: Date.parse("2026-03-01T00:00:00Z"),
  lastGeneratedAt: Date.parse("2026-03-01T00:00:00Z"),
  projectSectionId: "section-1",
  ...overrides,
});

describe("task time and duration", () => {
  afterEach(() => {
    vi.restoreAllMocks();
  });

  it("gives generated tasks the template time and duration", () => {
    const db = createDB();
    insertRows(db, {
      templates: [template({ time: "09:30", durationMinutes: 45 })],
    });

    syncDispatch(
      db,
      generateTasksForTemplate({
        templateId: "template-1",
        toDate: Date.parse("2026-03-03T12:00:00Z"),
      }),
    );

    const { tasks, entries } = allRows(db);
    expect(tasks).toHaveLength(3);
    expect(tasks.map((t) => t.durationMinutes)).toEqual([45, 45, 45]);
    expect(entries.map((e) => e.time)).toEqual(["09:30", "09:30", "09:30"]);
  });

  it("reads dated entries with their tasks for the requested dates only", () => {
    const db = createDB();
    insertRows(db, { tasks: [task("a"), task("b"), task("c")] });
    for (const [taskId, date] of [
      ["a", "2026-03-02"],
      ["b", "2026-03-02"],
      ["c", "2026-03-03"],
    ]) {
      syncDispatch(
        db,
        scheduleTask({ taskId, date, position: "append", time: null }),
      );
    }

    const rows = selectSync(db, {
      selector: datedEntriesByDates,
      args: { dates: ["2026-03-02", "2026-03-09"] },
    });
    expect(rows.map((r) => [r.date, r.task.id, r.entry.taskId])).toEqual([
      ["2026-03-02", "a", "a"],
      ["2026-03-02", "b", "b"],
    ]);
  });

  it("projects upcoming template occurrences exactly as generation creates them", () => {
    const db = createDB();
    insertRows(db, {
      templates: [
        template({
          time: "09:30",
          lastGeneratedAt: Date.parse("2026-03-02T12:00:00Z"),
        }),
      ],
    });

    const upcoming = selectSync(db, {
      selector: taskTemplateUpcomingOccurrences,
      args: {
        fromDate: Date.parse("2026-03-01T00:00:00Z"),
        toDate: Date.parse("2026-03-05T23:59:59Z"),
      },
    });
    // Mar 1 is behind lastGeneratedAt; Mar 2 is still generated by the
    // checkpoint's day.
    expect(upcoming.map((o) => [o.date, o.time])).toEqual([
      ["2026-03-02", "09:30"],
      ["2026-03-03", "09:30"],
      ["2026-03-04", "09:30"],
      ["2026-03-05", "09:30"],
    ]);

    syncDispatch(
      db,
      generateTasksForTemplate({
        templateId: "template-1",
        toDate: Date.parse("2026-03-05T12:00:00Z"),
      }),
    );

    const { entries } = allRows(db);
    expect(entries.map((e) => e.taskId).sort()).toEqual(
      upcoming.map((o) => o.id).sort(),
    );
    expect(
      selectSync(db, {
        selector: taskTemplateUpcomingOccurrences,
        args: {
          fromDate: Date.parse("2026-03-01T00:00:00Z"),
          toDate: Date.parse("2026-03-05T23:59:59Z"),
        },
      }),
    ).toEqual([]);
  });

  it("puts late-evening sub-daily occurrences on their local day", () => {
    const previousTZ = process.env.TZ;
    process.env.TZ = "America/New_York";
    try {
      const db = new DB(new BptreeInmemDriver(), {
        traits: [dbIdTrait("space", "a0000000-0000-4000-8000-000000000001")],
      });
      execSync(db.loadTables(registeredSpaceSyncableTables));
      // 20:00 on Mar 2 in New York (UTC-5).
      const start = Date.parse("2026-03-03T01:00:00Z");
      expect(new Date(start).getTimezoneOffset()).toBe(300);
      insertRows(db, {
        templates: [
          template({
            repeatRule: "FREQ=HOURLY;INTERVAL=1",
            repeatRuleDtStart: start,
            createdAt: start,
            lastGeneratedAt: start,
          }),
        ],
      });
      // 23:30 on Mar 2 in New York.
      const toDate = Date.parse("2026-03-03T04:30:00Z");

      const upcoming = selectSync(db, {
        selector: taskTemplateUpcomingOccurrences,
        args: { fromDate: start, toDate },
      });
      expect(upcoming).toHaveLength(3);
      expect(upcoming.every((o) => o.date === "2026-03-02")).toBe(true);

      syncDispatch(
        db,
        generateTasksForTemplate({ templateId: "template-1", toDate }),
      );
      const { entries } = allRows(db);
      const mar2 = selectSync(db, {
        selector: dailyListByDate,
        args: { date: "2026-03-02" },
      });
      expect(entries).toHaveLength(upcoming.length);
      expect(entries.every((e) => e.dailyListId === mar2?.id)).toBe(true);
    } finally {
      if (previousTZ === undefined) delete process.env.TZ;
      else process.env.TZ = previousTZ;
    }
  });

  it("ignores the template time for sub-daily rules", () => {
    const db = createDB();
    insertRows(db, {
      templates: [
        template({
          repeatRule: "FREQ=MINUTELY;INTERVAL=30",
          time: "09:30",
        }),
      ],
    });

    syncDispatch(
      db,
      generateTasksForTemplate({
        templateId: "template-1",
        toDate: Date.parse("2026-03-01T00:45:00Z"),
      }),
    );

    const { entries } = allRows(db);
    expect(entries.length).toBeGreaterThan(0);
    expect(entries.every((e) => e.time == null)).toBe(true);
  });

  it("keeps the time across reschedules and drops it when unscheduled", () => {
    const db = createDB();
    insertRows(db, { tasks: [task("task-1")] });

    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-01",
        position: "append",
        time: "10:00",
      }),
    );
    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-02",
        position: "append",
      }),
    );
    expect(entryOf(db, "task-1")?.time).toBe("10:00");

    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-02",
        position: "append",
        time: null,
      }),
    );
    expect(entryOf(db, "task-1")?.time).toBeNull();

    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-02",
        position: "append",
        time: "11:00",
      }),
    );
    syncDispatch(db, removeFromDailyList({ taskId: "task-1" }));
    expect(entryOf(db, "task-1")).toBeUndefined();

    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-03",
        position: "append",
      }),
    );
    expect(entryOf(db, "task-1")?.time).toBeUndefined();
  });

  it("carries time and duration over when a task becomes a template", () => {
    const db = createDB();
    const now = Date.parse("2026-03-04T17:05:00Z");
    insertRows(db, { tasks: [task("task-1")] });
    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-04",
        position: "append",
        time: "08:15",
      }),
    );
    syncDispatch(
      db,
      updateTask({ id: "task-1", task: { durationMinutes: 20 } }),
    );
    const current = selectSync(db, {
      selector: taskById,
      args: { id: "task-1" },
    })!;

    const created = syncDispatch(
      db,
      createTaskTemplateFromTask({ task: current, data: {}, now }),
    );

    expect(created.time).toBe("08:15");
    expect(created.durationMinutes).toBe(20);
    const { tasks, entries } = allRows(db);
    expect(tasks).toHaveLength(1);
    expect(tasks[0].durationMinutes).toBe(20);
    expect(entries).toHaveLength(1);
    expect(entries[0].time).toBe("08:15");
  });

  it("rejects malformed times and durations", () => {
    const db = createDB();
    insertRows(db, { tasks: [task("task-1")], templates: [template({})] });

    expect(() =>
      syncDispatch(
        db,
        scheduleTask({
          taskId: "task-1",
          date: "2026-03-01",
          position: "append",
          time: "9:00",
        }),
      ),
    ).toThrow(/Invalid task time/);
    expect(() =>
      syncDispatch(
        db,
        updateTask({ id: "task-1", task: { durationMinutes: 0 } }),
      ),
    ).toThrow(/Invalid task duration/);
    expect(() =>
      syncDispatch(
        db,
        updateTemplate({ id: "template-1", template: { time: "24:00" } }),
      ),
    ).toThrow(/Invalid task time/);
  });

  it("round-trips time and duration through backups", () => {
    const db = createDB();
    insertRows(db, {
      tasks: [{ ...task("task-1"), durationMinutes: 90 }],
      templates: [template({ time: "07:00", durationMinutes: 15 })],
    });
    syncDispatch(
      db,
      scheduleTask({
        taskId: "task-1",
        date: "2026-03-01",
        position: "append",
        time: "13:45",
      }),
    );
    const backup = selectSync(db, {
      selector: getSpaceBackup,
      args: {},
    }) as Backup;
    backup.projectSections = [
      {
        id: "section-1",
        title: "Section",
        projectId: "project-1",
        createdAt: 0,
        orderToken: "a0",
      },
    ];

    const restored = createDB();
    syncDispatch(restored, loadSpaceBackup({ backup }));

    expect(
      selectSync(restored, { selector: taskById, args: { id: "task-1" } })
        ?.durationMinutes,
    ).toBe(90);
    expect(entryOf(restored, "task-1")?.time).toBe("13:45");
    const restoredTemplate = syncDispatch(
      restored,
      action({
        name: "readRestoredTemplate",
        args: {},
        handler: function* () {
          return (yield* selectFrom(taskTemplatesTable, "byIds"))[0];
        },
      })({}),
    );
    expect(restoredTemplate?.time).toBe("07:00");
    expect(restoredTemplate?.durationMinutes).toBe(15);
  });

  it("drops malformed time and duration values from restored backups", () => {
    const warn = vi.spyOn(console, "warn").mockImplementation(() => {});
    const backup: Backup = {
      projects: [],
      dailyLists: [{ id: "list-1", date: "2026-03-01" }],
      projectSections: [
        {
          id: "section-1",
          title: "Section",
          projectId: "project-1",
          createdAt: 0,
          orderToken: "a0",
        },
      ],
      tasks: [
        {
          id: "task-1",
          title: "Bad",
          state: "todo",
          projectSectionId: "section-1",
          orderToken: "a0",
          lastToggledAt: 0,
          createdAt: 0,
          templateId: null,
          templateDate: null,
          durationMinutes: 0,
        },
        {
          id: "task-2",
          title: "Good",
          state: "todo",
          projectSectionId: "section-1",
          orderToken: "a1",
          lastToggledAt: 0,
          createdAt: 0,
          templateId: null,
          templateDate: null,
          durationMinutes: 30,
        },
      ],
      dailyEntries: [
        {
          id: "entry-1",
          taskId: "task-1",
          orderToken: "a0",
          listId: "list-1",
          createdAt: 0,
          time: "25:00",
        },
        {
          id: "entry-2",
          taskId: "task-2",
          orderToken: "a1",
          listId: "list-1",
          createdAt: 0,
          time: "08:00",
        },
      ],
      taskTemplates: [
        {
          id: "template-1",
          title: "Bad template",
          orderToken: "a0",
          repeatRule: "FREQ=DAILY;INTERVAL=1",
          createdAt: 0,
          lastGeneratedAt: 0,
          projectSectionId: "section-1",
          time: "9am",
          durationMinutes: 1.5,
        },
      ],
    };

    const db = createDB();
    syncDispatch(db, loadSpaceBackup({ backup }));

    const task = (id: string) =>
      selectSync(db, { selector: taskById, args: { id } });
    expect(task("task-1")).toBeDefined();
    expect(task("task-1")?.durationMinutes).toBeUndefined();
    expect(task("task-2")?.durationMinutes).toBe(30);
    expect(entryOf(db, "task-1")).toBeDefined();
    expect(entryOf(db, "task-1")?.time).toBeUndefined();
    expect(entryOf(db, "task-2")?.time).toBe("08:00");
    const restoredTemplate = syncDispatch(
      db,
      action({
        name: "readRestoredBadTemplate",
        args: {},
        handler: function* () {
          return (yield* selectFrom(taskTemplatesTable, "byIds"))[0];
        },
      })({}),
    );
    expect(restoredTemplate?.time).toBeUndefined();
    expect(restoredTemplate?.durationMinutes).toBeUndefined();
    expect(warn).toHaveBeenCalledTimes(4);
  });
});
